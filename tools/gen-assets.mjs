// Bundles static/ into src/assets.js (Workers serve them from memory; no build step on Cloudflare).
// Run after editing anything in static/:  node tools/gen-assets.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
const types = { css: "text/css; charset=utf-8", js: "text/javascript; charset=utf-8", svg: "image/svg+xml" };
const out = {};
for (const f of readdirSync("static").sort()) {
  const body = readFileSync(`static/${f}`, "utf8");
  out[f] = { type: types[f.split(".").pop()], body, etag: createHash("sha1").update(body).digest("hex").slice(0, 12) };
}
writeFileSync("src/assets.js", "// GENERATED by tools/gen-assets.mjs from static/. Do not edit.\nexport const ASSETS = " + JSON.stringify(out, null, 0) + ";\n");
console.log("assets:", Object.keys(out).join(", "));
