# Writes the CSS that gives every platform logo the same visual weight (run after adding a logo to static/net-*.png).
import math, re, glob
from PIL import Image
AREA_CARD, AREA_TILE = 1500, 2100
# Logos that look heavier than their area (dense, tall letters) get a smaller share.
WEIGHT = {"smashloud": 0.72}
lines = ["/* Logos balanced by area (generated by tools/logo-sizes.py) */"]
for f in sorted(glob.glob("static/net-*.png")):
    k = f.split("net-")[1][:-4]
    w, h = Image.open(f).size
    r = w / h
    wt = WEIGHT.get(k, 1)
    def dims(area, hmax):
        hh = min(hmax, math.sqrt(area * wt / r)); return round(hh * r), round(hh)
    cw, ch = dims(AREA_CARD, 24); tw, th = dims(AREA_TILE, 30)
    lines.append(f".net-logo.nl-{k} {{ width: {cw}px; height: {ch}px; }} .plat-tile .net-logo.nl-{k}, .plat-setup .net-logo.nl-{k} {{ width: {tw}px; height: {th}px; }}")
css = open("static/app.css").read()
css = re.sub(r"\n/\* Logos balanced by area \(generated.*?\*/\n(?:\.net-logo\.nl-.*\n|\.plat-tile .*\n)*", "\n", css)
css = re.sub(r"\n\.net-logo \{ object-fit: contain; max-width: none; \}\n", "\n", css)
css = css.rstrip("\n") + "\n" + "\n".join(lines) + "\n.net-logo { object-fit: contain; max-width: none; }\n"
open("static/app.css", "w").write(css)
print("\n".join(lines))
